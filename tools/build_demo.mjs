import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function buildDemo(){
 const metadata=JSON.parse(await readFile(resolve(root,'assets/demo/matrix.json'),'utf8'));
 const base64=(await readFile(resolve(root,'assets/demo/MATRIX.EV'))).toString('base64');
 await writeFile(resolve(root,'web/demo.js'),'/* Generated by tools/build_demo.mjs. */\nconst EV_DEMO='+JSON.stringify({...metadata,base64})+';\n');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildDemo();
